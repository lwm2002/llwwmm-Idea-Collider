export const categories = Object.keys(catalog);
export const concepts: Concept[] = Object.entries(catalog).flatMap(([category, rows]) =>
  rows
    .split('\n')
    .filter(Boolean)
    .map((row) => {
      const [name, description, properties, functions, constraints, tags] = row.split('|');
      return {
        id: name,
        name,
        category,
        description,
        properties: properties.split(','),
        functions: functions.split(','),
        constraints: constraints.split(','),
        tags: tags.split(','),
        relatedConcepts: [],
      };
    }),
);
for (const c of concepts) {
  c.relatedConcepts = concepts
    .filter((other) => other.id !== c.id)
    .map((other) => ({
      id: other.id,
      score:
        other.tags.filter((t) => c.tags.includes(t)).length * 2 +
        Number(other.category === c.category),
    }))
    .sort((a, b) => b.score - a.score)
    .slice(0, 3)
    .map((x) => x.id);
}
